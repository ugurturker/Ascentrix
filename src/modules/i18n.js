export { I18N };
export function curLang() {
  try { const l = userData.settings.lang; return (l === 'en' || l === 'de') ? l : 'tr'; } catch (e) { return 'tr'; }
}
export function t(key, params) {
  const lang = curLang();
  let s = I18N[lang] && I18N[lang][key] !== undefined ? I18N[lang][key] : I18N.tr[key];
  if (s === undefined) return key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? params[k] : m));
  return s;
}
export function L(obj) {
  if (obj == null) return '';
  if (typeof obj === 'string') return obj;
  const lang = curLang();
  return obj[lang] !== undefined ? obj[lang] : obj.tr;
}
export function setLang(lang) {
  if (!I18N[lang]) return;
  userData.settings.lang = lang;
  saveUserData();
  applyLang();
}
export function logLocale() {
  const lang = curLang();
  return lang === 'en' ? 'en-US' : lang === 'de' ? 'de-DE' : 'tr-TR';
}
export function applyLang() {
  // lazy import to avoid cycle: dynamic import of ui functions if needed
  const lang = curLang();
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.getAttribute('data-i18n-ph')); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.getAttribute('data-i18n-title')); });
  document.querySelectorAll('.lang-btn').forEach(b => { b.classList.toggle('active', b.dataset.lang === lang); });
  document.documentElement.lang = lang;
  document.title = t('appDocTitle');
  // UI updates will be triggered via event / direct calls from app.js to avoid circular deps
  window.dispatchEvent(new CustomEvent('langchange'));
}
